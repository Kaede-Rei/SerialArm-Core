void check(bool value,const char* reason){if(!value)throw std::runtime_error(reason);}
constexpr auto continuous=SoftFollowingPolicy::CONTINUOUS_GOVERNED_PATH;

void recorded_near_soft_bias() {
    const auto recorded=evaluate({-.3728},{-.4316843},{-.0073},{5.4});
    check(recorded.valid && !recorded.hard_violation && recorded.state==State::PAUSE_FOR_FEEDBACK,
        "the archived near-soft residual must remain visible as a soft following diagnostic");
    check(std::abs(recorded.max_error-.0588843)<1e-12 && std::abs(recorded.soft_limit[0]-.0588)<1e-12 &&
        std::abs(recorded.hard_limit[0]-.14)<1e-12,"the reported soft and hard limits must not be changed to hide the residual");
    check(should_pause_for_feedback(recorded) && !reference_progress_allowed(recorded),
        "default bounded catch-up consumers must retain their explicit frozen-reference behavior");
    check(!should_pause_for_feedback(recorded,continuous) && reference_progress_allowed(recorded,continuous),
        "continuous gravity acquisition must not wait for an equilibrium offset to cross its soft diagnostic");
    const auto requested=std::vector<double>{.03};
    check(command_velocity(requested,should_pause_for_feedback(recorded,continuous))==requested &&
        command_velocity(requested,should_pause_for_feedback(recorded))[0]==0,
        "the existing governed reference derivative must remain live during acquisition instead of snapping to zero");
    const auto initial=Heartbeat::TimePoint{};
    Heartbeat old(initial);old.begin_catchup(initial);old.command_sent(initial+std::chrono::milliseconds(1200));
    old.control_cycle_received(initial+std::chrono::milliseconds(1200));
    check(old.catchup_expired(initial+std::chrono::milliseconds(1201),false) &&
        !old.feedback_stalled(initial+std::chrono::milliseconds(1201)),
        "the original 1.2 second catch-up timeout must remain distinct from a live control heartbeat");
}

void persistent_offset_and_hard_boundaries() {
    for(std::size_t n:{1,3,7}) {
        std::vector<double> r(n),q(n),v(n),max_v(n,5.4);
        for(std::size_t i=0;i<n;++i){r[i]=.1*i;q[i]=r[i]-(i==n/2?.0588843:.02+.002*i);v[i]=-.0073;}
        const auto a=evaluate(r,q,v,max_v);
        check(reference_progress_allowed(a,continuous) && !reference_progress_allowed(a),
            "a mapped stable near-soft offset must continue governed acquisition for arbitrary joint counts");
        auto rr=r,qq=q,vv=v;std::reverse(rr.begin(),rr.end());std::reverse(qq.begin(),qq.end());std::reverse(vv.begin(),vv.end());
        const auto permuted=evaluate(rr,qq,vv,max_v);
        check(permuted.worst_joint==n-1-a.worst_joint && reference_progress_allowed(permuted,continuous),
            "joint permutation must only permute the responsible feedback coordinate");
        for(unsigned frame=0;frame<4000;++frame) {
            for(std::size_t i=0;i<n;++i){r[i]+=.0001;q[i]+=.0001;}
            const auto following=evaluate(r,q,v,max_v);
            check(reference_progress_allowed(following,continuous) && search_progress_scale(following)>0 &&
                should_pause_for_feedback(following),
                "persistent soft bias must not manufacture convergence or stop positive path progress");
        }
        q[n/2]=r[n/2]-.14;
        const auto hard=evaluate(r,q,v,max_v);
        check(hard.hard_violation && !reference_progress_allowed(hard,continuous) && search_progress_scale(hard)==0,
            "the unchanged hard following boundary must stop every progress policy");
        q[n/2]=std::numeric_limits<double>::quiet_NaN();
        check(!reference_progress_allowed(evaluate(r,q,v,max_v),continuous),
            "invalid physical feedback must never be treated as a benign steady bias");
    }
    Heartbeat heartbeat(Heartbeat::TimePoint{});
    const auto late=Heartbeat::TimePoint{}+std::chrono::milliseconds(66);
    check(heartbeat.feedback_stalled(late),"continuous acquisition must not extend the independent 65ms feedback deadline");
}

// A sampled MIT port with an unmodelled constant gravity/load residual. Its
// equilibrium offset straddles the soft threshold even when it follows a
// moving reference; feedback is generated by integration, never replaced with
// a desired response. The old frozen-point policy cannot remove this bias.
void sampled_biased_mit_complete_path() {
    constexpr double dt=.001,source_duration=5,pi=3.14159265358979323846;
    for(std::size_t n:{1,3,7}) {
        std::vector<double> q(n,-.0588843),v(n,0),ref(n,0),ref_v(n,0),max_v(n,5.4),max_a(n,8);
        const double slew=search_governor_slew_limit(max_v,max_a,200);
        double source=0,scale=1,maximum_error=0,maximum_reference_acceleration=0;std::size_t soft_frames=0;
        auto previous_v=ref_v;bool finished=false;
        for(std::size_t tick=0;tick<60000;++tick) {
            if(tick%5==0) {
                const auto status=evaluate(ref,q,v,max_v);
                check(reference_progress_allowed(status,continuous),
                    "a healthy biased MIT replay must retain continuous governed source progress below the real hard bound");
                soft_frames+=status.state==State::PAUSE_FOR_FEEDBACK;
                maximum_error=std::max(maximum_error,status.max_error);
                const double desired=search_progress_scale(status);
                scale+=std::clamp(desired-scale,-slew,slew);
                source=std::min(source_duration,source+scale*.005);
                for(std::size_t i=0;i<n;++i) {
                    const double amplitude=.15+.01*i;
                    ref[i]=amplitude*(1-std::cos(pi*source/source_duration));
                    ref_v[i]=amplitude*pi/source_duration*std::sin(pi*source/source_duration)*scale;
                    maximum_reference_acceleration=std::max(maximum_reference_acceleration,std::abs(ref_v[i]-previous_v[i])/.005);
                }
                previous_v=ref_v;
                if(source>=source_duration){finished=true;break;}
            }
            for(std::size_t i=0;i<n;++i) {
                const double P=4.7619*(1+.1*i),D=.1209*(1+.1*i),I=.05*(1+.1*i);
                const double acceleration=(P*(ref[i]-q[i])+D*(ref_v[i]-v[i])-P*.0588843)/I;
                v[i]+=acceleration*dt;q[i]+=v[i]*dt;
            }
        }
        check(finished && soft_frames>100 && maximum_error<.14 && maximum_reference_acceleration<8,
            "the physical biased plant must finish its original smooth path despite sustained soft-error diagnostics");
        std::cout<<n<<" biased MIT axes: complete_source="<<source<<"s soft_frames="<<soft_frames
            <<" peak_error="<<maximum_error<<"rad reference_acceleration="<<maximum_reference_acceleration<<"rad/s2\n";
    }
}
